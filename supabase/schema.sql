create or replace function public.viole_list_chats(p_user_id text)
returns table (
  id text,
  type text,
  name text,
  avatar_color text,
  owner_id text,
  created_at timestamptz,
  updated_at timestamptz,
  member_ids text[],
  read_at jsonb,
  last_message jsonb,
  unread_count bigint
)
language sql
security definer
set search_path = public
stable
as $$
  select
    c.id,
    c.type,
    c.name,
    c.avatar_color,
    c.owner_id,
    c.created_at,
    c.updated_at,
    (
      select coalesce(array_agg(cm.user_id order by cm.user_id), array[]::text[])
      from public.viole_chat_members cm
      where cm.chat_id = c.id
    ) as member_ids,
    case
      when mine.read_at is null then '{}'::jsonb
      else jsonb_build_object(p_user_id, mine.read_at)
    end as read_at,
    (
      select to_jsonb(m)
      from public.viole_messages m
      where m.chat_id = c.id
        and (c.type <> 'group' or m.created_at >= mine.joined_at)
      order by m.created_at desc
      limit 1
    ) as last_message,
    (
      select count(*)
      from public.viole_messages m
      where m.chat_id = c.id
        and m.sender_id <> p_user_id
        and (c.type <> 'group' or m.created_at >= mine.joined_at)
        and (mine.read_at is null or m.created_at > mine.read_at)
    ) as unread_count
  from public.viole_chat_members mine
  join public.viole_chats c on c.id = mine.chat_id
  where mine.user_id = p_user_id
  order by c.updated_at desc;
$$;

create or replace function public.viole_create_direct_chat(
  p_chat_id text,
  p_user_a text,
  p_user_b text,
  p_created_at timestamptz
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_key text;
  v_chat_id text;
begin
  if p_user_a = p_user_b then
    raise exception 'A direct chat requires two different users';
  end if;

  v_key := least(p_user_a, p_user_b) || ':' || greatest(p_user_a, p_user_b);

  insert into public.viole_chats (id, type, direct_key, created_at, updated_at)
  values (p_chat_id, 'direct', v_key, p_created_at, p_created_at)
  on conflict (direct_key) do update set direct_key = excluded.direct_key
  returning id into v_chat_id;

  insert into public.viole_chat_members (chat_id, user_id, joined_at)
  values (v_chat_id, p_user_a, p_created_at), (v_chat_id, p_user_b, p_created_at)
  on conflict (chat_id, user_id) do nothing;

  return v_chat_id;
end;
$$;

create or replace function public.viole_create_group_chat(
  p_chat_id text,
  p_owner_id text,
  p_name text,
  p_avatar_color text,
  p_member_ids text[],
  p_created_at timestamptz
)
returns text
language plpgsql
security definer
set search_path = public
as $$
begin
  if cardinality(coalesce(p_member_ids, array[]::text[])) > 49 then
    raise exception 'A group cannot contain more than 50 members';
  end if;

  insert into public.viole_chats (
    id, type, name, avatar_color, owner_id, created_at, updated_at
  ) values (
    p_chat_id, 'group', p_name, p_avatar_color, p_owner_id, p_created_at, p_created_at
  );

  insert into public.viole_chat_members (chat_id, user_id, joined_at)
  select p_chat_id, member_id, p_created_at
  from (
    select distinct unnest(coalesce(p_member_ids, array[]::text[]) || array[p_owner_id]) as member_id
  ) members;

  return p_chat_id;
end;
$$;

revoke all on function public.viole_list_chats(text) from public, anon, authenticated;
revoke all on function public.viole_create_direct_chat(text, text, text, timestamptz) from public, anon, authenticated;
revoke all on function public.viole_create_group_chat(text, text, text, text, text[], timestamptz) from public, anon, authenticated;

grant execute on function public.viole_list_chats(text) to service_role;
grant execute on function public.viole_create_direct_chat(text, text, text, timestamptz) to service_role;
grant execute on function public.viole_create_group_chat(text, text, text, text, text[], timestamptz) to service_role;

-- Public profile-media bucket: files can be viewed by URL. Uploads and deletes are
-- performed only by the trusted Node.js backend with the secret/service-role key.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'profile-media',
  'profile-media',
  true,
  8388608,
  array['image/png', 'image/jpeg', 'image/webp', 'image/gif']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
