-- Viole / Flovifly database schema for Supabase.
-- Run this complete file in Supabase Dashboard -> SQL Editor.
-- It is safe to re-run after an earlier version of the schema.

create table if not exists public.viole_users (
  id text primary key,
  username varchar(24) not null unique check (username ~ '^[a-z0-9_]{4,24}$'),
  password_hash text not null,
  display_name varchar(32) not null,
  bio varchar(160) not null default '',
  status varchar(40) not null default 'На связи',
  avatar_color text not null default 'violet',
  is_owner boolean not null default false,
  is_premium boolean not null default false,
  avatar_animated boolean not null default false,
  avatar_url text,
  avatar_path text,
  avatar_is_gif boolean not null default false,
  banner_url text,
  banner_path text,
  banner_is_gif boolean not null default false,
  nick_color varchar(7),
  nick_gradient jsonb,
  nick_animation text not null default 'none',
  created_at timestamptz not null default now()
);

create table if not exists public.viole_chats (
  id text primary key,
  type text not null check (type in ('direct', 'group')),
  name varchar(40),
  avatar_color text,
  owner_id text references public.viole_users(id) on delete set null,
  direct_key text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (type = 'direct' and direct_key is not null)
    or (type = 'group' and direct_key is null)
  )
);

create table if not exists public.viole_chat_members (
  chat_id text not null references public.viole_chats(id) on delete cascade,
  user_id text not null references public.viole_users(id) on delete cascade,
  read_at timestamptz,
  joined_at timestamptz not null default now(),
  primary key (chat_id, user_id)
);

create table if not exists public.viole_messages (
  id text primary key,
  chat_id text not null references public.viole_chats(id) on delete cascade,
  sender_id text not null references public.viole_users(id) on delete cascade,
  text varchar(4000) not null,
  reply_to jsonb,
  reactions jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.viole_calls (
  id text primary key,
  chat_id text not null references public.viole_chats(id) on delete cascade,
  participant_ids jsonb not null,
  type text not null check (type in ('audio', 'video')),
  state text not null check (state in ('ringing', 'active', 'rejected', 'ended')),
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.viole_sessions (
  id text primary key,
  user_id text not null references public.viole_users(id) on delete cascade,
  token_hash varchar(64) not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  expires_at timestamptz not null,
  revoked_at timestamptz,
  user_agent_hash varchar(64),
  ip_hash varchar(64),
  check (expires_at > created_at)
);

create table if not exists public.viole_storage_cleanup (
  id bigint generated by default as identity primary key,
  object_path text not null unique,
  attempts integer not null default 0 check (attempts >= 0),
  last_error varchar(500) not null default '',
  created_at timestamptz not null default now(),
  next_attempt_at timestamptz not null default now()
);

create index if not exists viole_chat_members_user_id_idx
  on public.viole_chat_members(user_id, chat_id);
create index if not exists viole_messages_chat_created_idx
  on public.viole_messages(chat_id, created_at desc);
create index if not exists viole_messages_sender_idx
  on public.viole_messages(sender_id);
create index if not exists viole_chats_updated_idx
  on public.viole_chats(updated_at desc);
create index if not exists viole_sessions_user_idx
  on public.viole_sessions(user_id, expires_at desc);
create index if not exists viole_sessions_expiry_idx
  on public.viole_sessions(expires_at);
create index if not exists viole_storage_cleanup_due_idx
  on public.viole_storage_cleanup(next_attempt_at);

alter table public.viole_users enable row level security;
alter table public.viole_chats enable row level security;
alter table public.viole_chat_members enable row level security;
alter table public.viole_messages enable row level security;
alter table public.viole_calls enable row level security;
alter table public.viole_sessions enable row level security;
alter table public.viole_storage_cleanup enable row level security;

